#include <iostream>
#include <cmath>

using std::cout;

int main() {
    cout << sqrt(25) << "\n";// for square root
    cout << pow(2, 3) << "\n";// for power
    cout << remainder(10, 3) << "\n";// for remainder
    cout << fmax(10, 20) << "\n";// for maximum from passed values
    cout << ceil(10.5) << "\n";// for ceiling value
    cout << floor(10.5) << "\n";// for floor value
    cout << trunc(10.5) << "\n";// for trunc value
    cout << round(10.49) << "\n";// for round value

    return 0;
}